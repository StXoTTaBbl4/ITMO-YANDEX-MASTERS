# Основная теорема арифметики говорит: любое число раскладывается на произведение простых множителей единственным образом, с точностью до их перестановки.
# Например:Число 8 можно представить как 2×2×2. Число 50 –— как 2×5×5 (или 5×5×2, или 5×2×5). Три варианта отличаются лишь порядком следования множителей.
# Разложение числа на простые множители называется факторизацией числа.
# Напишите программу, которая производит факторизацию переданного числа.
# Формат ввода
# В единственной строке дано число n ( 2≤n≤10^9 ), которое нужно факторизовать.
# Формат вывода
# Выведите в порядке неубывания простые множители, на которые раскладывается число n.
n = int(input())

multipliers = []
d = 2

while d * d <= n:
    while n % d == 0:
        multipliers.append(d)
        n //= d
    d += 1

if n > 1:
    multipliers.append(n)

print(' '.join(map(str, multipliers)))
