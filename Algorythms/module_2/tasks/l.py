# У Тимофея было очень много стажёров, целых N (0≤N≤10^6 ) человек. Каждый стажёр хотел быть лучше своих предшественников, поэтому 
# i-й стажёр делал столько коммитов, сколько делали два предыдущих стажёра в сумме. 
# Два первых стажёра были менее инициативными — они сделали по одному коммиту.
# Пусть Fi  —– число коммитов, сделанных i-м стажёром (стажёры нумеруются с нуля). 
# Тогда выполняется следующее: 
# F_0=F_1 = 1. Для всех i≥2 выполнено F_i = F_i-1 + F_i-2
# Определите, сколько кода напишет следующий стажёр –— найдите последние k цифр числа F n
# Как найти k последних цифр
# Чтобы вычислить k последних цифр некоторого числа x, достаточно взять остаток от его деления на число 10^k. 
# Эта операция обозначается как x mod 10^k
# Узнайте, как записывается операция взятия остатка по модулю в вашем языке программирования.
# Также обратите внимание на возможное переполнение целочисленных типов, если в вашем языке такое случается.
# Формат ввода
# В первой строке записаны через пробел два целых числа 
# n (0≤n≤10^6 ) и k (1≤k≤8).
# Формат вывода
# Выведите единственное число – последние k цифр числа F_n
n, k = map(int, input().split())
mod = 10 ** k

if n <= 1:
    print(1 % mod)

else:
    prev, curr = 1, 1
    for _ in range(2, n + 1):
        prev, curr = curr, (prev + curr) % mod

    print(curr)
