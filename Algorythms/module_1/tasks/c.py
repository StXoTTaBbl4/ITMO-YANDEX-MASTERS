# Дана матрица. Нужно написать функцию, которая для элемента возвращает всех его соседей.
# Соседним считается элемент, находящийся от текущего на одну ячейку влево, вправо, вверх или вниз.
# Диагональные элементы соседними не считаются.
# Формат ввода
# В первой строке задано n — количество строк матрицы. Во второй — количество столбцов m.
# Числа m и n не превосходят 1000. В следующих n строках задана матрица.
# Элементы матрицы — целые числа, по модулю не превосходящие
# 1000. В последних двух строках записаны координаты элемента, соседей которого нужно найти. Индексация начинается с нуля.
# Формат вывода
# Напечатайте нужные числа в возрастающем порядке через пробел.
n = int(input())
m = int(input())
matrix = [list(map(int, input().split())) for _ in range(n)]
row = int(input())
col = int(input())

neighbors = []
if col - 1 >= 0:
    neighbors.append(matrix[row][col - 1])
if col + 1 < m:
    neighbors.append(matrix[row][col + 1])
if row - 1 >= 0:
    neighbors.append(matrix[row - 1][col])
if row + 1 < n:
    neighbors.append(matrix[row + 1][col])

neighbors.sort()
print(*neighbors)
