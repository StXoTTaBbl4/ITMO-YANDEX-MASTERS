# Тимофей записал два числа в двоичной системе счисления и попросил Гошу вывести их сумму, также в двоичной системе.
# Встроенную в язык программирования возможность сложения двоичных чисел применять нельзя. Помогите Гоше решить задачу.
# Решение должно работать за O(N), где N –— количество разрядов максимального числа на входе.
# Формат ввода
# Два числа в двоичной системе счисления, каждое на отдельной строке. Длина каждого числа не превосходит 10000 символов.
# Формат вывода
# Одно число в двоичной системе счисления.
a = input()
b = input()

max_len = max(len(a), len(b))
a = a.zfill(max_len)
b = b.zfill(max_len)

result = []
carry = 0

for i in range(max_len - 1, -1, -1):
    total = int(a[i]) + int(b[i]) + carry
    result.append(str(total % 2))
    carry = total // 2

if carry:
    result.append('1')

print(''.join(reversed(result)))
